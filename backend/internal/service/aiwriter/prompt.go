func userPrompt(in Input) string {
	var b strings.Builder
	b.WriteString("Контекст:\n")
	if in.Name != "" {
		fmt.Fprintf(&b, "Ім'я гіда: %s\n", in.Name)
	}
	if in.City != "" {
		fmt.Fprintf(&b, "Місто: %s\n", in.City)
	}
	if in.Kind == KindExcursion && in.Title != "" {
		fmt.Fprintf(&b, "Назва екскурсії: %s\n", in.Title)
	}
	b.WriteString("\nВихідний текст:\n<<<\n")
	b.WriteString(in.Text)
	b.WriteString("\n>>>")
	return b.String()
}
