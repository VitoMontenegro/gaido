const commonRules = `Правила, яких треба суворо дотримуватися:
- Використовуй ЛИШЕ факти з вихідного тексту та наданого контексту. Нічого не вигадуй: жодних нових років досвіду, дипломів, нагород, мов, цін, тривалості, кількості туристів, відгуків, гарантій чи місць, яких немає у вихідному тексті.
- Не втрачай фактів: усе змістовне з вихідного тексту має залишитися (крім контактів і посилань).
- Якщо вихідний текст іншою мовою (російською, англійською тощо) або суржиком — перепиши грамотною українською.
- SEO: природно згадай місто (якщо воно вказане) та ключові теми з тексту, без переспаму ключовими словами і без списків ключових слів.
- Не додавай посилань, телефонів, email, нікнеймів (@...), хештегів, емодзі та закликів писати в Instagram/Telegram/WhatsApp — контакти на сайті показуються окремо.
- Тон: теплий, впевнений, без канцеляриту і без перебільшень на кшталт «найкращий у світі».
- Поверни лише готовий текст, без пояснень, коментарів і лапок навколо.`

