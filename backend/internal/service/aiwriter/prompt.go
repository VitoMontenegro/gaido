const commonRules = `Правила, яких треба суворо дотримуватися. Порушення будь-якого пункту робить відповідь непридатною:
- Нічого не вигадуй. Єдине джерело фактів — вихідний текст між <<< >>> і рядки контексту. Не доповнюй текст власними знаннями про міста, країни, пам'ятки чи типову біографію гіда.
- Географія — закритий список. Місто, країну, район або пам'ятку можна назвати лише якщо ця назва дослівно є у вихідному тексті або в рядку «Місто». Інше місце заборонене: не підставляй відоме туристичне місто, столицю чи «логічну» локацію. Якщо міста немає ні в тексті, ні в рядку «Місто» — не називай жодного міста і не натякай на країну.
- Не замінюй місто з вихідного тексту іншим. Якщо у тексті одне місто, а в рядку «Місто» інше — залиш обидва й не додавай третього.
- Не додавай років досвіду, дипломів, професій, освіти, нагород, мов, цін, тривалості, кількості туристів, відгуків і гарантій, якщо їх немає у вихідному тексті.
- Не втрачай фактів: усе змістовне з вихідного тексту має залишитися (крім контактів і посилань).
- Якщо вихідний текст іншою мовою (російською, англійською тощо) або суржиком — перепиши грамотною українською, фактів не змінюй.
- SEO: якщо рядок «Місто» є — згадай саме це місто один або два рази. Теми бери тільки з тексту. Без переспаму і без списку ключових слів.
- Не додавай посилань, телефонів, email, нікнеймів (@...), хештегів, емодзі та закликів писати в Instagram/Telegram/WhatsApp — контакти на сайті показуються окремо.
- Тон: теплий, впевнений, без канцеляриту і без перебільшень на кшталт «найкращий у світі». Краще коротший текст, ніж новий факт.
- Поверни лише готовий текст, без пояснень, коментарів і лапок навколо.`

