func userPrompt(in Input) string {
	var b strings.Builder
	b.WriteString("Контекст (єдині факти поза вихідним текстом):\n")
	if in.Name != "" {
		fmt.Fprintf(&b, "Ім'я гіда: %s\n", in.Name)
	} else {
		b.WriteString("Ім'я гіда: не вказано. Не вигадуй ім'я.\n")
	}
	if in.City != "" {
		fmt.Fprintf(&b, "Місто: %s\n", in.City)
		fmt.Fprintf(&b, "Дозволене місто з контексту: %s. Інші міста й країни можна згадувати лише якщо вони дослівно є у вихідному тексті.\n", in.City)
	} else {
		b.WriteString("Місто: не вказано. Не називай жодного міста чи країни, яких немає дослівно у вихідному тексті.\n")
	}
	if in.Kind == KindExcursion && in.Title != "" {
		fmt.Fprintf(&b, "Назва екскурсії: %s\n", in.Title)
	}
	b.WriteString("\nВихідний текст:\n<<<\n")
	b.WriteString(in.Text)
	b.WriteString("\n>>>\n")
	b.WriteString("Перепиши текст. Не додавай місць, професій і фактів, яких немає вище.")
	return b.String()
}
